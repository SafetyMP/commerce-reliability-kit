import assert from 'node:assert/strict';
import { scenarios, evaluateScenario } from '../apps/demo/src/evaluator.ts';
const ids = ['partial-shipment','normal-delay','missing-order','inventory-buffer','stale-evidence','duplicate-shipment'];
assert.deepEqual(scenarios.map(s=>s.id).sort(), [...ids].sort());
const faulty = evaluateScenario('partial-shipment','faulty');
const fixed = evaluateScenario('partial-shipment','corrected');
assert.equal(faulty.metrics.ordered,5); assert.equal(faulty.metrics.fulfilled,3); assert.equal(faulty.metrics.outstanding,2);
assert(faulty.assertions.some(a=>a.status==='FAIL')); assert(fixed.assertions.every(a=>a.status==='PASS'));
assert.deepEqual(faulty.observations,fixed.observations); assert.deepEqual(faulty.coverage,fixed.coverage);
assert.deepEqual(fixed,evaluateScenario('partial-shipment','corrected'));
const absent=evaluateScenario('missing-order','corrected');
assert(absent.findings.length>0); assert(absent.assertions.some(a=>a.status==='PASS'));
const inventory=evaluateScenario('inventory-buffer','corrected');
assert.equal(inventory.findings.length,0); assert(inventory.assertions.every(a=>a.status==='PASS'));
const stale=evaluateScenario('stale-evidence','corrected');
assert(stale.assertions.some(a=>a.status==='INCONCLUSIVE')); assert(!JSON.stringify(stale.findings).toLowerCase().includes('shortage'));
const duplicate=evaluateScenario('duplicate-shipment','corrected');
assert.equal(duplicate.metrics.fulfilled,3); assert(duplicate.assertions.every(a=>a.status==='PASS'));
assert.throws(()=>evaluateScenario('inventory-buffer','corrected',{buffer:-1}));
assert.notDeepEqual(evaluateScenario('inventory-buffer','corrected',{buffer:0}),inventory);
console.log('Protected frontend gate PASS: six fixtures, 5/3/2, same inputs, deterministic execution, expected absence, buffer, stale uncertainty, deduplication, policy validation.');
